export type ReviewableCard = { flashcardId: string; topicId: string }

/**
 * Kartın kullanıcı için gerçekten okunabilir olup olmadığını doğrular.
 *
 * Bu, `reviewCard` action'ının SAHİPLİK denetimidir: RLS başkasının kişisel
 * kartını zaten döndürmez, burada satır bulunamazsa istek reddedilir. Bir
 * Server Action herkese açık bir uçtur; istemcinin gönderdiği kimliğe
 * güvenilmez.
 */
export async function findReviewableCard(
  client: Client,
  flashcardId: string,
): Promise<ReviewableCard | null> {
  const { data, error } = await client
    .from('flashcards')
    .select('id, topic_id')
    .eq('id', flashcardId)
    .eq('is_published', true)
    .is('deleted_at', null)
    .maybeSingle()

  if (error) throw new AppError('internal', 'Kart okunamadı.')
  return data ? { flashcardId: data.id, topicId: data.topic_id } : null
}

/** Kullanıcının bu karta ait SM-2 satırı. Yoksa null. */
export async function getCardReview(
  client: Client,
  userId: string,
  flashcardId: string,
): Promise<ReviewRow | null> {
  const { data, error } = await client
    .from('card_reviews')
    .select('flashcard_id, ease_factor, interval_days, repetitions, next_review_at, last_grade')
    .eq('user_id', userId)
    .eq('flashcard_id', flashcardId)
    .maybeSingle()

  if (error) throw new AppError('internal', 'Tekrar geçmişi okunamadı.')
  return data ?? null
}

/** SM-2 sonucunu yazar. Satır yoksa açılır, varsa güncellenir. */
export async function upsertCardReview(
  client: Client,
  input: {
    userId: string
    flashcardId: string
    easeFactor: number
    intervalDays: number
    repetitions: number
    nextReviewAt: string
    lastGrade: number
    lastReviewedAt: string
  },
): Promise<void> {
  const { error } = await client.from('card_reviews').upsert(
    {
      user_id: input.userId,
      flashcard_id: input.flashcardId,
      // numeric(4,2): iki basamağa yuvarlanmazsa Postgres zaten yuvarlar,
      // ama o zaman bir sonraki hesap veritabanındaki değerle sürdüğü için
      // yuvarlama burada açıkça yapılır.
      ease_factor: Math.round(input.easeFactor * 100) / 100,
      interval_days: input.intervalDays,
      repetitions: input.repetitions,
      next_review_at: input.nextReviewAt,
      last_grade: input.lastGrade,
      last_reviewed_at: input.lastReviewedAt,
    },
    { onConflict: 'user_id,flashcard_id' },
  )

  if (error) throw new AppError('internal', 'Tekrar kaydedilemedi.')
}

