/**
 * Hafıza kartı okumaları (spec §M9).
 *
 * Hepsi OTURUM istemcisiyle çalışır: `flashcards` üzerindeki RLS zaten iki
 * grubu ayırır — editör kartları herkese açık, `auto_generated` kartlar
 * yalnızca sahibine. Yine de sorgular `created_by` / `auto_generated`
 * filtrelerini açıkça yazar (CONVENTIONS §3: yetki iki kez denetlenir; ayrıca
 * sorgu okunduğunda hangi grubun istendiği görünür olsun).
 *
 * Düz sorgu kuralı geçerlidir: iç içe select yok, ilişkiler JavaScript
 * tarafında birleştirilir.
 */

type Client = DataClient

/**
 * Vadesi gelmiş kartlar için taranacak en fazla `card_reviews` satırı.
 * Kotanın katıdır: konu süzgeci uygulandığında bir kısmı elenebileceği için
 * kotadan fazlası okunur.
 */
const DUE_SCAN_MULTIPLIER = 4

/** Hiç çalışılmamış kartlardan taranacak en fazla satır. */
const NEW_SCAN_MULTIPLIER = 4

export type CardTopic = {
  topicId: string
  title: string
  slug: string
  orderIndex: number
  unitId: string
  unitName: string
  subjectId: string
  subjectName: string
  subjectOrderIndex: number
}

export type FlashcardItem = {
  flashcardId: string
  topicId: string
  front: string
  back: string
  imageUrl: string | null
  autoGenerated: boolean
  createdAt: string
}

export type ReviewQueue = {
  cards: QueuedCard[]
  /** Kotaya kırpılmadan önce vadesi gelmiş toplam kart sayısı. */
  dueTotal: number
}

/* ------------------------------------------------------------------------- *
 * Konu kapsamı
 * ------------------------------------------------------------------------- */

/**
 * Kullanıcının sınavındaki konular (ders → ünite → konu, üç düz sorgu).
 *
 * Kartlar konuya bağlıdır ama konunun sınavı ancak ders üzerinden bilinir;
 * `topics` tablosunda `exam_id` yoktur. Silinmiş ders/ünite/konu dışarıdadır:
 * müfredattan kaldırılmış bir konunun kartı bugünün destesine girmemeli.
 */
export async function getExamCardTopics(client: Client, examId: string): Promise<CardTopic[]> {
  const { data: subjects, error: subjectError } = await client
    .from('subjects')
    .select('id, name, order_index')
    .eq('exam_id', examId)
    .is('deleted_at', null)
    .order('order_index', { ascending: true })

  if (subjectError) throw new AppError('internal', 'Dersler yüklenemedi.')
  const subjectRows = subjects ?? []
  if (subjectRows.length === 0) return []

  const { data: units, error: unitError } = await client
    .from('units')
    .select('id, name, subject_id, order_index')
    .in(
      'subject_id',
      subjectRows.map((subject) => subject.id),
    )
    .is('deleted_at', null)
    .order('order_index', { ascending: true })

  if (unitError) throw new AppError('internal', 'Üniteler yüklenemedi.')
  const unitRows = units ?? []
  if (unitRows.length === 0) return []

  const { data: topics, error: topicError } = await client
    .from('topics')
    .select('id, title, slug, unit_id, order_index')
    .in(
      'unit_id',
      unitRows.map((unit) => unit.id),
    )
    .is('deleted_at', null)
    .order('order_index', { ascending: true })

  if (topicError) throw new AppError('internal', 'Konular yüklenemedi.')

  const subjectById = new Map(subjectRows.map((subject) => [subject.id, subject]))
  const unitById = new Map(unitRows.map((unit) => [unit.id, unit]))

  return (topics ?? []).flatMap((topic) => {
    const unit = unitById.get(topic.unit_id)
    const subject = unit ? subjectById.get(unit.subject_id) : undefined
    if (!unit || !subject) return []
    return [
      {
        topicId: topic.id,
        title: topic.title,
        slug: topic.slug,
        orderIndex: topic.order_index,
        unitId: unit.id,
        unitName: unit.name,
        subjectId: subject.id,
        subjectName: subject.name,
        subjectOrderIndex: subject.order_index,
      },
    ]
  })
}

/* ------------------------------------------------------------------------- *
 * Bugünün destesi
 * ------------------------------------------------------------------------- */

/**
 * "Bugün Tekrar" destesi.
 *
 * Dört düz sorgu, hepsi sınırlı:
 *   1. vadesi gelmiş `card_reviews` satırları (en eski önce),
 *   2. o satırların kartları (kapsam + yayın süzgeci burada uygulanır),
 *   3. kapsamdaki en eski kartlar (hiç çalışılmamış aday havuzu),
 *   4. o adayların halihazırda bir tekrar satırı olup olmadığı.
 *
 * Sıralama, vade sınırı ve kota `lib/cards/queue.ts` içindeki saf mantıkta
 * uygulanır; SQL yalnızca aday toplar. Böylece deste kuralları birim testiyle
 * kilitlenebiliyor.
 */
export async function getReviewQueue(
  client: Client,
  userId: string,
  options: { topicIds: readonly string[]; now?: Date; limit?: number } = { topicIds: [] },
): Promise<ReviewQueue> {
  const now = options.now ?? new Date()
  const limit = options.limit ?? DAILY_REVIEW_LIMIT
  const topicIds = [...options.topicIds]
  if (topicIds.length === 0 || limit <= 0) return { cards: [], dueTotal: 0 }

  const nowIso = now.toISOString()

  const { data: dueReviews, error: dueError } = await client
    .from('card_reviews')
    .select('flashcard_id, ease_factor, interval_days, repetitions, next_review_at, last_grade')
    .eq('user_id', userId)
    .lte('next_review_at', nowIso)
    .order('next_review_at', { ascending: true })
    .limit(limit * DUE_SCAN_MULTIPLIER)

  if (dueError) throw new AppError('internal', 'Tekrar destesi yüklenemedi.')
  const reviewRows = dueReviews ?? []

  const reviewById = new Map(reviewRows.map((row) => [row.flashcard_id, row]))

  const dueCards =
    reviewRows.length === 0
      ? []
      : await readCards(client, {
          topicIds,
          ids: reviewRows.map((row) => row.flashcard_id),
        })

  const newCandidates = await readCards(client, {
    topicIds,
    limit: limit * NEW_SCAN_MULTIPLIER,
    oldestFirst: true,
  })

  // Hiç çalışılmamış olanları ayıklamak için bu adayların tekrar satırlarına
  // bakılır; vadesi gelmemiş bir kart yeni sayılıp desteye girmemeli.
  const reviewedIds = await findReviewedFlashcardIds(
    client,
    userId,
    newCandidates.map((card) => card.flashcardId),
  )

  const candidates: QueueCandidate[] = [
    ...dueCards.map((card) => toCandidate(card, reviewById.get(card.flashcardId) ?? null)),
    ...newCandidates
      .filter((card) => !reviewedIds.has(card.flashcardId))
      .map((card) => toCandidate(card, null)),
  ]

  const cards = buildReviewQueue(candidates, now, limit)

  // Toplam, kotaya kırpılmadan önceki gerçek sayıdır; tamamlama ekranı
  // "yarına kalan" kart sayısını buradan söyler.
  const dueTotal = await countDueReviews(client, userId, nowIso)

  return { cards, dueTotal }
}

type ReviewRow = {
  flashcard_id: string
  ease_factor: number
  interval_days: number
  repetitions: number
  next_review_at: string
  last_grade: number | null
}

function toCandidate(card: FlashcardItem, review: ReviewRow | null): QueueCandidate {
  return {
    flashcardId: card.flashcardId,
    topicId: card.topicId,
    front: card.front,
    back: card.back,
    imageUrl: card.imageUrl,
    autoGenerated: card.autoGenerated,
    createdAt: card.createdAt,
    review: review
      ? {
          easeFactor: Number(review.ease_factor),
          intervalDays: review.interval_days,
          repetitions: review.repetitions,
          nextReviewAt: review.next_review_at,
          lastGrade: review.last_grade,
        }
      : null,
  }
}

/** Vadesi gelmiş kart sayısı (kotadan bağımsız). */
export async function countDueReviews(
  client: Client,
  userId: string,
  nowIso: string = new Date().toISOString(),
): Promise<number> {
  const { count, error } = await client
    .from('card_reviews')
    .select('flashcard_id', { count: 'exact', head: true })
    .eq('user_id', userId)
    .lte('next_review_at', nowIso)

  if (error) throw new AppError('internal', 'Tekrar sayısı okunamadı.')
  return count ?? 0
}

/** Verilen kartlardan hangilerinin tekrar satırı var? */
async function findReviewedFlashcardIds(
  client: Client,
  userId: string,
  flashcardIds: readonly string[],
): Promise<Set<string>> {
  if (flashcardIds.length === 0) return new Set()

  const { data, error } = await client
    .from('card_reviews')
    .select('flashcard_id')
    .eq('user_id', userId)
    .in('flashcard_id', [...flashcardIds])

  if (error) throw new AppError('internal', 'Tekrar geçmişi okunamadı.')
  return new Set((data ?? []).map((row) => row.flashcard_id))
}

