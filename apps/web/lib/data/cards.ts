/** Editörlerin hazırladığı, tüm öğrencilere açık kartlar. */
export async function getEditorCardsForTopic(
  client: Client,
  topicId: string,
  limit = 100,
): Promise<FlashcardItem[]> {
  return readCards(client, { topicIds: [topicId], autoGenerated: false, limit, oldestFirst: true })
}

/** Kullanıcının yanlışlarından üretilmiş kişisel kartları. */
export async function getOwnCardsForTopic(
  client: Client,
  userId: string,
  topicId: string,
  limit = 100,
): Promise<FlashcardItem[]> {
  return readCards(client, {
    topicIds: [topicId],
    autoGenerated: true,
    createdBy: userId,
    limit,
    oldestFirst: false,
  })
}

/** Konu başına kart sayısı — konu seçicide "12 kart" etiketi için. */
export async function countCardsByTopic(
  client: Client,
  topicIds: readonly string[],
): Promise<Map<string, number>> {
  if (topicIds.length === 0) return new Map()

  const { data, error } = await client
    .from('flashcards')
    .select('topic_id')
    .in('topic_id', [...topicIds])
    .eq('is_published', true)
    .is('deleted_at', null)

  if (error) throw new AppError('internal', 'Hafıza kartları yüklenemedi.')

  const counts = new Map<string, number>()
  for (const row of data ?? []) {
    counts.set(row.topic_id, (counts.get(row.topic_id) ?? 0) + 1)
  }
  return counts
}

/**
 * Kartı çalışma/gözatma için okur.
 *
 * `is_published` ve `deleted_at` süzgeçleri her okumada uygulanır: yayından
 * kaldırılmış bir kart destede de listede de görünmemeli.
 */
async function readCards(
  client: Client,
  options: {
    topicIds: readonly string[]
    ids?: readonly string[]
    autoGenerated?: boolean
    createdBy?: string
    limit?: number
    oldestFirst?: boolean
  },
): Promise<FlashcardItem[]> {
  if (options.topicIds.length === 0) return []
  if (options.ids && options.ids.length === 0) return []

  let query = client
    .from('flashcards')
    .select('id, topic_id, front, back, image_url, auto_generated, created_at')
    .in('topic_id', [...options.topicIds])
    .eq('is_published', true)
    .is('deleted_at', null)

  if (options.ids) query = query.in('id', [...options.ids])
  if (options.autoGenerated !== undefined) query = query.eq('auto_generated', options.autoGenerated)
  if (options.createdBy !== undefined) query = query.eq('created_by', options.createdBy)

  query = query.order('created_at', { ascending: options.oldestFirst !== false })
  if (options.limit !== undefined) query = query.limit(options.limit)

  const { data, error } = await query
  if (error) throw new AppError('internal', 'Hafıza kartları yüklenemedi.')

  return (data ?? []).map((row) => ({
    flashcardId: row.id,
    topicId: row.topic_id,
    front: row.front,
    back: row.back,
    imageUrl: row.image_url,
    autoGenerated: row.auto_generated,
    createdAt: row.created_at,
  }))
}

